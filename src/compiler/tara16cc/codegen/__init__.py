"""Stage 4: the TARA16 code generator.

The generator is one class assembled from four mixins, one per file, so
each file can be read on its own:

    target.py    registers, the instruction buffer, addresses  (the machine)
    expr.py      expressions                                   (values)
    stmt.py      statements                                    (control flow)
    func.py      variables, prologue, epilogue, data           (functions)
    peephole.py  the clean-up pass

`gen_program` walks the list of functions and globals the parser produced
and returns assembly text for tara16cc.asm.
"""
from ..inline import inline_program
from .expr import ExprMixin
from .func import FuncMixin
from .peephole import PeepholeMixin
from .stmt import StmtMixin
from .target import TargetMixin


class Gen(TargetMixin, ExprMixin, StmtMixin, FuncMixin, PeepholeMixin):
    def __init__(self, opt):
        self.opt = opt
        self.items = []
        self.functions = []
        self.label_no = 0
        self.depth = 0
        self.pool = 0
        self.base_pool = 0
        self.live_regs = None       # per tick: registers of living variables
        self.cur_tick = -1
        self.live_during = 0
        self.ntick = 0
        self.busy = 0
        self.saved = 0
        self.save_lr = True
        self.frame_size = 0
        self.ret_label = None
        self.ret_direct = False
        self.made_call = False
        self.cur_fn = None
        self.cur_tok = None
        self.cse_var = None
        self.cse_reg = -1
        self.body_start = 0
        self.body_end = 0
        self.fn_has_bitfield_store = False
        self.globals_by_name = {}
        self.icall_used = False
        self.epi_used = False


def gen_program(prog, opt, source_name=''):
    """Turn the parser's output into TARA16 assembly text."""
    if opt.inline:
        inline_program(prog)
    g = Gen(opt)
    g.globals_by_name = {v.name: v for v in prog}
    out = ['; generated by tara16cc (tara16-abi0)']
    for fn in prog:
        if not fn.is_function or not fn.is_definition or not fn.is_live:
            continue
        g.gen_function(fn)
    g.flush_functions(out)
    g.emit_data(prog, out)
    return '\n'.join(out) + '\n'
